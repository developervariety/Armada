namespace Armada.Core.Protocol
{
    using System;
    using System.Collections.Generic;
    using System.Text.Json.Serialization;

    /// <summary>
    /// One JSONL record of <c>pi -p --mode json</c>, discriminated by <c>type</c>. Only lines whose <c>type</c> is one of
    /// pi's event types (<see cref="KnownTypes"/>) are treated as protocol events; any other line (including JSON a model
    /// printed) is not. Records are split on LF only; a trailing CR is ignored.
    /// </summary>
    public class PiStreamEvent
    {
        #region Public-Members

        /// <summary>session (header, first line; emitted even with --no-session).</summary>
        public const string TypeSession = "session";

        /// <summary>agent_start.</summary>
        public const string TypeAgentStart = "agent_start";

        /// <summary>agent_end (one low-level run ended; <c>willRetry</c> says whether pi retries).</summary>
        public const string TypeAgentEnd = "agent_end";

        /// <summary>agent_settled (no automatic work remains: the true end of the run).</summary>
        public const string TypeAgentSettled = "agent_settled";

        /// <summary>turn_start.</summary>
        public const string TypeTurnStart = "turn_start";

        /// <summary>turn_end.</summary>
        public const string TypeTurnEnd = "turn_end";

        /// <summary>message_start.</summary>
        public const string TypeMessageStart = "message_start";

        /// <summary>message_update (streaming delta with cumulative usage).</summary>
        public const string TypeMessageUpdate = "message_update";

        /// <summary>message_end (authoritative final message).</summary>
        public const string TypeMessageEnd = "message_end";

        /// <summary>tool_execution_start.</summary>
        public const string TypeToolExecutionStart = "tool_execution_start";

        /// <summary>tool_execution_update.</summary>
        public const string TypeToolExecutionUpdate = "tool_execution_update";

        /// <summary>tool_execution_end.</summary>
        public const string TypeToolExecutionEnd = "tool_execution_end";

        /// <summary>auto_retry_start.</summary>
        public const string TypeAutoRetryStart = "auto_retry_start";

        /// <summary>auto_retry_end.</summary>
        public const string TypeAutoRetryEnd = "auto_retry_end";

        /// <summary>
        /// The pi event types Armada recognizes as protocol lines (the ones it reads plus the ones it ignores).
        /// </summary>
        public static readonly IReadOnlySet<string> KnownTypes = new HashSet<string>(StringComparer.Ordinal)
        {
            TypeSession, TypeAgentStart, TypeAgentEnd, TypeAgentSettled, TypeTurnStart, TypeTurnEnd,
            TypeMessageStart, TypeMessageUpdate, TypeMessageEnd,
            TypeToolExecutionStart, TypeToolExecutionUpdate, TypeToolExecutionEnd,
            TypeAutoRetryStart, TypeAutoRetryEnd,
            "compaction_start", "compaction_end", "queue_update",
            "summarization_retry_scheduled", "summarization_retry_attempt_start", "summarization_retry_finished"
        };

        /// <summary>
        /// Event type.
        /// </summary>
        [JsonPropertyName("type")]
        public string? Type { get; set; } = null;

        /// <summary>
        /// Session header format version, or null.
        /// </summary>
        [JsonPropertyName("version")]
        public int? Version { get; set; } = null;

        /// <summary>
        /// Session id of the header, or null.
        /// </summary>
        [JsonPropertyName("id")]
        public string? Id { get; set; } = null;

        /// <summary>
        /// Working directory of the session header, or null.
        /// </summary>
        [JsonPropertyName("cwd")]
        public string? Cwd { get; set; } = null;

        /// <summary>
        /// Message of message_start / message_end / turn_end, or null.
        /// </summary>
        [JsonPropertyName("message")]
        public PiMessage? Message { get; set; } = null;

        /// <summary>
        /// Messages generated by the run (agent_end), or null.
        /// </summary>
        [JsonPropertyName("messages")]
        public List<PiMessage>? Messages { get; set; } = null;

        /// <summary>
        /// Whether pi retries after this agent_end, or null.
        /// </summary>
        [JsonPropertyName("willRetry")]
        public bool? WillRetry { get; set; } = null;

        /// <summary>
        /// Whether the settled run was aborted (agent_settled), or null.
        /// </summary>
        [JsonPropertyName("aborted")]
        public bool? Aborted { get; set; } = null;

        /// <summary>
        /// Streaming delta of message_update, or null.
        /// </summary>
        [JsonPropertyName("assistantMessageEvent")]
        public PiAssistantMessageEvent? AssistantMessageEvent { get; set; } = null;

        /// <summary>
        /// Cumulative usage of the response in progress (message_update), or null. Never summed.
        /// </summary>
        [JsonPropertyName("usage")]
        public PiUsage? Usage { get; set; } = null;

        /// <summary>
        /// Tool call id of a tool_execution_* event, or null.
        /// </summary>
        [JsonPropertyName("toolCallId")]
        public string? ToolCallId { get; set; } = null;

        /// <summary>
        /// Tool name of a tool_execution_* event, or null.
        /// </summary>
        [JsonPropertyName("toolName")]
        public string? ToolName { get; set; } = null;

        /// <summary>
        /// Tool arguments of a tool_execution_* event as raw JSON, or null.
        /// </summary>
        [JsonPropertyName("args")]
        [JsonConverter(typeof(RawJsonStringConverter))]
        public string? Args { get; set; } = null;

        /// <summary>
        /// Tool result of tool_execution_end as raw JSON (see <see cref="PiToolResult.TextOf"/>), or null.
        /// </summary>
        [JsonPropertyName("result")]
        [JsonConverter(typeof(RawJsonStringConverter))]
        public string? Result { get; set; } = null;

        /// <summary>
        /// Whether a tool execution failed (tool_execution_end), or null.
        /// </summary>
        [JsonPropertyName("isError")]
        public bool? IsError { get; set; } = null;

        /// <summary>
        /// Tool execution duration in milliseconds (tool_execution_end), or null.
        /// </summary>
        [JsonPropertyName("durationMs")]
        public long? DurationMs { get; set; } = null;

        /// <summary>
        /// Retry attempt number (auto_retry_*), or null.
        /// </summary>
        [JsonPropertyName("attempt")]
        public int? Attempt { get; set; } = null;

        /// <summary>
        /// Maximum retry attempts (auto_retry_start), or null.
        /// </summary>
        [JsonPropertyName("maxAttempts")]
        public int? MaxAttempts { get; set; } = null;

        /// <summary>
        /// Delay before the retry in milliseconds (auto_retry_start), or null.
        /// </summary>
        [JsonPropertyName("delayMs")]
        public long? DelayMs { get; set; } = null;

        /// <summary>
        /// Error that caused a retry (auto_retry_start), or null.
        /// </summary>
        [JsonPropertyName("errorMessage")]
        public string? ErrorMessage { get; set; } = null;

        /// <summary>
        /// Whether the retries succeeded (auto_retry_end), or null.
        /// </summary>
        [JsonPropertyName("success")]
        public bool? Success { get; set; } = null;

        /// <summary>
        /// Final error after the retries failed (auto_retry_end), or null.
        /// </summary>
        [JsonPropertyName("finalError")]
        public string? FinalError { get; set; } = null;

        /// <summary>
        /// Reply text streamed by a <c>text_delta</c> update, or null for any other event (thinking is not reply text).
        /// </summary>
        [JsonIgnore]
        public string? TextDelta
        {
            get
            {
                if (!String.Equals(Type, TypeMessageUpdate, StringComparison.Ordinal) || AssistantMessageEvent == null) return null;
                if (!String.Equals(AssistantMessageEvent.Type, PiAssistantMessageEvent.TypeTextDelta, StringComparison.Ordinal)) return null;
                return String.IsNullOrEmpty(AssistantMessageEvent.Delta) ? null : AssistantMessageEvent.Delta;
            }
        }

        /// <summary>
        /// Thinking text streamed by a <c>thinking_delta</c> update, or null.
        /// </summary>
        [JsonIgnore]
        public string? ThinkingDelta
        {
            get
            {
                if (!String.Equals(Type, TypeMessageUpdate, StringComparison.Ordinal) || AssistantMessageEvent == null) return null;
                if (!String.Equals(AssistantMessageEvent.Type, PiAssistantMessageEvent.TypeThinkingDelta, StringComparison.Ordinal)) return null;
                return String.IsNullOrEmpty(AssistantMessageEvent.Delta) ? null : AssistantMessageEvent.Delta;
            }
        }

        /// <summary>
        /// The assistant message of an assistant <c>message_end</c> (one per model response), or null.
        /// </summary>
        [JsonIgnore]
        public PiMessage? AssistantMessageEnd
        {
            get
            {
                if (!String.Equals(Type, TypeMessageEnd, StringComparison.Ordinal)) return null;
                return Message != null && Message.IsAssistant ? Message : null;
            }
        }

        /// <summary>
        /// True for a record that ends the run with no more automatic work: <c>agent_settled</c>, or <c>agent_end</c>
        /// whose <c>willRetry</c> is not true.
        /// </summary>
        [JsonIgnore]
        public bool IsRunEnd
        {
            get
            {
                if (String.Equals(Type, TypeAgentSettled, StringComparison.Ordinal)) return true;
                return String.Equals(Type, TypeAgentEnd, StringComparison.Ordinal) && WillRetry != true;
            }
        }

        /// <summary>
        /// The last assistant message of an <c>agent_end</c>, or null.
        /// </summary>
        [JsonIgnore]
        public PiMessage? LastAssistantMessage
        {
            get
            {
                if (Messages == null) return null;
                for (int i = Messages.Count - 1; i >= 0; i--)
                {
                    if (Messages[i] != null && Messages[i].IsAssistant) return Messages[i];
                }

                return null;
            }
        }

        #endregion

        #region Public-Methods

        /// <summary>
        /// Try to parse one stdout line as a pi protocol event. A trailing CR is stripped; the line must be a single JSON
        /// object whose <c>type</c> is in <see cref="KnownTypes"/>.
        /// </summary>
        /// <param name="line">Raw line.</param>
        /// <param name="evt">The event, or null.</param>
        /// <returns>True when the line is a pi protocol event.</returns>
        public static bool TryParse(string? line, out PiStreamEvent? evt)
        {
            evt = null;
            if (String.IsNullOrEmpty(line)) return false;
            string trimmed = line!.TrimEnd('\r');
            if (trimmed.IndexOf("\"type\"", StringComparison.Ordinal) < 0) return false;
            if (!RuntimeStreamJson.TryDeserializeLine(trimmed, out PiStreamEvent? parsed) || parsed == null) return false;
            if (parsed.Type == null || !KnownTypes.Contains(parsed.Type)) return false;
            evt = parsed;
            return true;
        }

        #endregion
    }
}
