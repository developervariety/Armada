namespace Armada.Core.Services
{
    using System;
    using System.Collections.Generic;
    using System.IO;
    using System.Linq;
    using System.Threading;
    using System.Threading.Tasks;
    using Armada.Core.Models;

    /// <summary>Prepare generated artifacts in an owned detached worktree without publishing its candidate.</summary>
    public static class GeneratedArtifactLanding
    {
        /// <summary>Validate an optional persisted declaration without touching the filesystem.</summary>
        public static string? ValidateDeclaration(GeneratedArtifactPolicy? policy)
        {
            if (policy == null) return null;
            if (String.IsNullOrWhiteSpace(policy.RegenerateCommand) || policy.Paths == null || policy.Paths.Count == 0)
                return "generated_declaration_incomplete";
            HashSet<string> unique = new HashSet<string>(StringComparer.Ordinal);
            foreach (string path in policy.Paths)
                if (String.IsNullOrWhiteSpace(path) || Path.IsPathRooted(path) || path.Contains('\\')
                    || path.Split('/').Any(part => part.Length == 0 || part == "." || part == ".." || part.Equals(".git", StringComparison.OrdinalIgnoreCase))
                    || !unique.Add(path)) return "generated_path_invalid";
            return null;
        }

        /// <summary>
        /// Merge authored changes and regenerate declared artifacts. The caller owns the worktree and supplies a
        /// bounded, leased command runner. A changed artifact relative to the reviewed source needs a fresh review.
        /// </summary>
        public static Task<GeneratedArtifactLandingResult> PrepareAsync(
            string worktree, string sourceRef, GeneratedArtifactPolicy? policy,
            Func<string[], CancellationToken, Task<GeneratedArtifactGitOutput>> git,
            Func<string, CancellationToken, Task<int>> runCommand,
            CancellationToken token = default) => PrepareCoreAsync(worktree, sourceRef, policy, git, runCommand, false, token);

        /// <summary>Rebase an existing review binding onto changed inputs and require a new verdict even when generated bytes match.</summary>
        public static Task<GeneratedArtifactLandingResult> PrepareBoundCandidateAsync(
            string worktree, string sourceRef, GeneratedArtifactPolicy? policy,
            Func<string[], CancellationToken, Task<GeneratedArtifactGitOutput>> git,
            Func<string, CancellationToken, Task<int>> runCommand,
            CancellationToken token = default) => PrepareCoreAsync(worktree, sourceRef, policy, git, runCommand, true, token);

        private static async Task<GeneratedArtifactLandingResult> PrepareCoreAsync(
            string worktree, string sourceRef, GeneratedArtifactPolicy? policy,
            Func<string[], CancellationToken, Task<GeneratedArtifactGitOutput>> git,
            Func<string, CancellationToken, Task<int>> runCommand, bool requireFreshReview, CancellationToken token)
        {
            if (git == null) throw new ArgumentNullException(nameof(git));
            if (runCommand == null) throw new ArgumentNullException(nameof(runCommand));
            GeneratedArtifactLandingResult result = new GeneratedArtifactLandingResult();
            if (policy == null) return result;
            try
            {
                string root = Path.GetFullPath(worktree);
                string[] paths = ValidatePaths(root, policy);
                result.TargetBaseCommit = await RequiredGitAsync(git, token, "rev-parse", "--verify", "HEAD^{commit}").ConfigureAwait(false);
                result.SourceCommit = await RequiredGitAsync(git, token, "rev-parse", "--verify", "--end-of-options", sourceRef + "^{commit}").ConfigureAwait(false);
                if ((await RequiredGitAsync(git, token, "status", "--porcelain", "--untracked-files=all", "--ignored=matching").ConfigureAwait(false)).Length != 0)
                    return Failed(result, "generated_worktree_dirty");
                GeneratedArtifactGitOutput forward = await git(new[] { "merge-base", "--is-ancestor", result.TargetBaseCommit, result.SourceCommit }, token).ConfigureAwait(false);
                if (forward.ExitCode == 0)
                {
                    if (requireFreshReview)
                    {
                        result.Outcome = "ReviewRequired";
                        result.Reason = "generated_candidate_base_changed";
                        result.CandidateCommit = result.SourceCommit;
                    }
                    return result;
                }
                if (forward.ExitCode != 1) return Failed(result, "generated_ancestry_probe_failed");

                foreach (string commit in new[] { result.TargetBaseCommit, result.SourceCommit })
                    foreach (string path in paths)
                        await RefuseTreeLinksAsync(git, commit, path, token).ConfigureAwait(false);

                // Equal artifact trees need no regeneration and retain the ordinary landing path.
                string[] difference = new[] { "diff", "--name-only", "-z", result.TargetBaseCommit, result.SourceCommit, "--" }
                    .Concat(paths.Select(Literal)).ToArray();
                if (!requireFreshReview && (await RequiredGitAsync(git, token, difference).ConfigureAwait(false)).Length == 0) return result;

                // Make the generated side identical to the landing base before Git merges authored paths.
                // Git therefore never text-merges generated bytes. Both original authored histories remain parents.
                await RequiredGitAsync(git, token, "checkout", "--detach", result.SourceCommit).ConfigureAwait(false);
                ValidatePaths(root, policy);
                await RequiredGitAsync(git, token, new[] { "restore", "--source=" + result.TargetBaseCommit, "--staged", "--worktree", "--" }
                    .Concat(paths.Select(Literal)).ToArray()).ConfigureAwait(false);
                if ((await RequiredGitAsync(git, token, "diff", "--cached", "--name-only").ConfigureAwait(false)).Length != 0)
                    await RequiredGitAsync(git, token, "commit", "-m", "Prepare generated artifacts from landing base").ConfigureAwait(false);
                string preparedSource = await RequiredGitAsync(git, token, "rev-parse", "HEAD").ConfigureAwait(false);
                await RequiredGitAsync(git, token, "checkout", "--detach", result.TargetBaseCommit).ConfigureAwait(false);
                GeneratedArtifactGitOutput merge = await git(new[] { "merge", "--no-ff", "--no-commit", preparedSource }, token).ConfigureAwait(false);
                if (merge.ExitCode != 0)
                {
                    string conflicts = await RequiredGitAsync(git, token, "diff", "--name-only", "--diff-filter=U").ConfigureAwait(false);
                    return Failed(result, "generated_authored_conflict: " + conflicts);
                }
                string mergedTree = await RequiredGitAsync(git, token, "write-tree").ConfigureAwait(false);
                ValidatePaths(root, policy);
                try
                {
                    if (await runCommand(policy.RegenerateCommand, token).ConfigureAwait(false) != 0)
                        return Failed(result, "generated_command_failed");
                }
                catch (OperationCanceledException) { throw; }
                catch (Exception ex)
                {
                    return Failed(result, "generated_command_failed: " + ex.GetType().Name);
                }
                ValidatePaths(root, policy);
                if (!String.Equals(result.TargetBaseCommit, await RequiredGitAsync(git, token, "rev-parse", "HEAD").ConfigureAwait(false), StringComparison.Ordinal))
                    return Failed(result, "generated_command_changed_head");

                string changed = await RequiredGitAsync(git, token, "diff", "--name-only", "-z", mergedTree).ConfigureAwait(false);
                string untracked = await RequiredGitAsync(git, token, "ls-files", "--others", "-z").ConfigureAwait(false);
                HashSet<string> allowed = new HashSet<string>(paths, StringComparer.Ordinal);
                string[] outside = GitDiffPaths.SplitNulSeparated(changed).Concat(GitDiffPaths.SplitNulSeparated(untracked))
                    .Where(path => !allowed.Contains(path)).Distinct(StringComparer.Ordinal).ToArray();
                if (outside.Length != 0) return Failed(result, "generated_undeclared_write: " + String.Join(", ", outside));
                await RequiredGitAsync(git, token, new[] { "add", "-A", "--" }.Concat(paths.Select(Literal)).ToArray()).ConfigureAwait(false);
                await RequiredGitAsync(git, token, "commit", "-m", "Merge authored changes and regenerate declared artifacts").ConfigureAwait(false);
                result.CandidateCommit = await RequiredGitAsync(git, token, "rev-parse", "HEAD").ConfigureAwait(false);
                string artifactDelta = await RequiredGitAsync(git, token, new[] { "diff", "--name-only", "-z", result.SourceCommit, result.CandidateCommit, "--" }
                    .Concat(paths.Select(Literal)).ToArray()).ConfigureAwait(false);
                result.Outcome = artifactDelta.Length == 0 && !requireFreshReview ? "Regenerated" : "ReviewRequired";
                result.Reason = requireFreshReview ? "generated_candidate_base_changed"
                    : artifactDelta.Length == 0 ? "generated_artifacts_match_reviewed_source" : "generated_candidate_requires_review";
                return result;
            }
            catch (OperationCanceledException) { throw; }
            catch (Exception ex) when (ex is InvalidOperationException || ex is IOException || ex is UnauthorizedAccessException
                || ex is ArgumentException || ex is TimeoutException || ex is System.ComponentModel.Win32Exception)
            {
                return Failed(result, "generated_preparation_failed: " + ex.Message);
            }
        }

        private static string Literal(string path) => ":(literal)" + path;

        private static GeneratedArtifactLandingResult Failed(GeneratedArtifactLandingResult result, string reason)
        {
            result.Outcome = "Failed";
            result.Reason = reason;
            return result;
        }

        private static string[] ValidatePaths(string root, GeneratedArtifactPolicy policy)
        {
            string? refusal = ValidateDeclaration(policy);
            if (refusal != null) throw new ArgumentException(refusal);
            if (new DirectoryInfo(root).LinkTarget != null) throw new ArgumentException("generated_symlink_escape");
            HashSet<string> unique = new HashSet<string>(StringComparer.Ordinal);
            foreach (string path in policy.Paths)
            {
                unique.Add(path);
                string current = root;
                foreach (string part in path.Split('/'))
                {
                    current = Path.Combine(current, part);
                    FileSystemInfo entry = Directory.Exists(current) ? new DirectoryInfo(current) : new FileInfo(current);
                    if (entry.LinkTarget != null) throw new ArgumentException("generated_symlink_escape");
                }
            }
            return unique.ToArray();
        }

        private static async Task RefuseTreeLinksAsync(Func<string[], CancellationToken, Task<GeneratedArtifactGitOutput>> git,
            string commit, string path, CancellationToken token)
        {
            string prefix = String.Empty;
            foreach (string part in path.Split('/'))
            {
                prefix = prefix.Length == 0 ? part : prefix + "/" + part;
                string entry = await RequiredGitAsync(git, token, "ls-tree", commit, "--", Literal(prefix)).ConfigureAwait(false);
                if (entry.StartsWith("120000 ", StringComparison.Ordinal) || entry.StartsWith("160000 ", StringComparison.Ordinal))
                    throw new ArgumentException("generated_symlink_escape");
            }
        }

        private static async Task<string> RequiredGitAsync(Func<string[], CancellationToken, Task<GeneratedArtifactGitOutput>> git,
            CancellationToken token, params string[] args)
        {
            GeneratedArtifactGitOutput result = await git(args, token).ConfigureAwait(false);
            if (result.ExitCode != 0) throw new InvalidOperationException("git " + args[0] + " failed (exit " + result.ExitCode + ")");
            return result.StandardOutput.TrimEnd('\r', '\n');
        }
    }
}
