namespace Armada.Core.Services
{
    using System;
    using System.IO;

    /// <summary>
    /// The project <c>.pi/mcp.json</c> Armada writes into a pi captain's working directory to bind the Armada MCP server
    /// (pi has no per-invocation MCP flag). The file carries <c>${ARMADA_MCP_TOKEN}</c>, never the token, and is marked
    /// with <see cref="GeneratedDescription"/> so leftovers from a crashed launch can be recognized and removed.
    /// </summary>
    public static class PiProjectMcpConfig
    {
        #region Public-Members

        /// <summary>
        /// Path of the file relative to the working directory.
        /// </summary>
        public static readonly string RelativePath = Path.Combine(".pi", "mcp.json");

        /// <summary>
        /// The <c>description</c> Armada gives its server entries; it identifies a file Armada generated.
        /// </summary>
        public const string GeneratedDescription = "Armada orchestration tools (missions, voyages, captains, fleets, memory). Generated by Armada for this launch.";

        /// <summary>
        /// pi tool exposure for the Armada server: its tools are loaded with tool_search instead of being declared up
        /// front, because Armada has many tools.
        /// </summary>
        public const string Exposure = "deferred";

        #endregion

        #region Public-Methods

        /// <summary>
        /// Whether file contents were generated by Armada (they carry <see cref="GeneratedDescription"/> and the token
        /// environment reference, never a token).
        /// </summary>
        /// <param name="contents">File contents, or null.</param>
        /// <returns>True for an Armada-generated file.</returns>
        public static bool IsGenerated(string? contents)
        {
            if (String.IsNullOrEmpty(contents)) return false;
            return contents!.Contains(GeneratedDescription, StringComparison.Ordinal)
                && contents.Contains("${" + CaptainThreadMcpPlanner.TokenEnvironmentVariable + "}", StringComparison.Ordinal);
        }

        /// <summary>
        /// Remove an Armada-generated <c>.pi/mcp.json</c> left in a working directory (for example by a launch whose
        /// Admiral crashed before the process exit was handled), and the <c>.pi</c> directory when it is then empty. A file
        /// Armada did not generate is never touched. Never throws.
        /// </summary>
        /// <param name="workingDirectory">The working directory (dock), or null.</param>
        /// <returns>True when a generated file was removed.</returns>
        public static bool RemoveGenerated(string? workingDirectory)
        {
            if (String.IsNullOrWhiteSpace(workingDirectory)) return false;
            try
            {
                string path = Path.Combine(workingDirectory!, RelativePath);
                if (!File.Exists(path)) return false;
                if (!IsGenerated(File.ReadAllText(path))) return false;
                File.Delete(path);
                string? directory = Path.GetDirectoryName(path);
                if (directory != null && Directory.Exists(directory) && Directory.GetFileSystemEntries(directory).Length == 0)
                    Directory.Delete(directory);
                return true;
            }
            catch
            {
                return false;
            }
        }

        #endregion
    }
}
